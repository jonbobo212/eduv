/* ---------- language ---------- */
const nodes = [...document.querySelectorAll('[data-i18n]')];
const EN = Object.fromEntries(nodes.map(n => [n.dataset.i18n, n.textContent]));

function setLang(lang) {
  const dict = lang === 'ru' ? RU : EN;
  for (const n of nodes) {
    const v = dict[n.dataset.i18n];
    if (v) n.textContent = v;
  }
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang button').forEach(b => b.classList.toggle('on', b.dataset.lang === lang));
  try { localStorage.setItem('aa-lang', lang); } catch {}
}
document.querySelectorAll('.lang button').forEach(b =>
  b.addEventListener('click', () => setLang(b.dataset.lang)));
try {
  const saved = localStorage.getItem('aa-lang');
  if (saved === 'ru') setLang('ru');
} catch { /* private mode - English stays */ }

/* ---------- header + drawer ---------- */
const hdr = document.getElementById('hdr');
const drawer = document.getElementById('drawer');
const burger = document.getElementById('burger');

addEventListener('scroll', () => hdr.classList.toggle('scrolled', scrollY > 24), { passive: true });

burger.addEventListener('click', () => {
  const open = drawer.classList.toggle('open');
  burger.setAttribute('aria-expanded', String(open));
  document.body.style.overflow = open ? 'hidden' : '';
});
drawer.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
  drawer.classList.remove('open');
  burger.setAttribute('aria-expanded', 'false');
  document.body.style.overflow = '';
}));

/* ---------- reveal on scroll ---------- */
const io = new IntersectionObserver((entries) => {
  for (const e of entries) {
    if (!e.isIntersecting) continue;
    e.target.classList.add('in');
    io.unobserve(e.target);
  }
}, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

document.querySelectorAll('.reveal').forEach((el, i) => {
  el.style.transitionDelay = `${Math.min(i % 4, 3) * 70}ms`;
  io.observe(el);
});

document.getElementById('yr').textContent = new Date().getFullYear();
